-- 1. /locations/12674 (Arlington National Cemetery): the new `episodes` collection.
SELECT e.ID_EPISODE, e.ID_SERIE, e.SEASON_NUMBER, e.EPISODE_NUMBER, e.EPISODE_TITLE,
       e.DAT_AIR, e.AIR_YEAR, e.STILL_PATH, e.IMDB_RATING, e.IMDB_VOTES,
       s.SERIE_TITLE, s.SERIE_TITLE_FR, s.POSTER_PATH,
       el.LOCATION_ROLE, COUNT(*) OVER() AS _TOTAL_COUNT
FROM T_WC_T2S_EPISODE_LOCATION el
JOIN T_WC_T2S_EPISODE e ON el.ID_EPISODE = e.ID_EPISODE AND COALESCE(e.DELETED, 0) = 0
JOIN T_WC_T2S_SERIE s ON e.ID_SERIE = s.ID_SERIE
WHERE el.ID_LOCATION = 12674 AND COALESCE(el.DELETED, 0) = 0
ORDER BY s.IMDB_RATING_WEIGHTED DESC, e.ID_SERIE ASC, e.SEASON_NUMBER ASC,
         e.EPISODE_NUMBER ASC, el.LOCATION_ROLE ASC
LIMIT 50;

SELECT ID_LOCATION, LOCATION_NAME, MOVIE_COUNT, SERIE_COUNT, EPISODE_COUNT
FROM T_WC_T2S_LOCATION WHERE ID_LOCATION = 12674;

-- 2. /episodes/688/1/10 (The West Wing, In Excelsis Deo): the new `locations` collection.
SELECT l.ID_LOCATION, l.LOCATION_NAME, l.LOCATION_NAME_FR, l.LOCATION_TYPE,
       l.POSTER_PATH, l.WIKIPEDIA_IMAGE_PATH,
       el.LOCATION_ROLE, el.DISPLAY_ORDER, COUNT(*) OVER() AS _TOTAL_COUNT
FROM T_WC_T2S_EPISODE_LOCATION el
JOIN T_WC_T2S_LOCATION l ON el.ID_LOCATION = l.ID_LOCATION AND l.DELETED = 0
WHERE el.ID_EPISODE = (SELECT e.ID_EPISODE FROM T_WC_T2S_EPISODE e
                       WHERE e.ID_SERIE = 688 AND e.SEASON_NUMBER = 1 AND e.EPISODE_NUMBER = 10
                       ORDER BY COALESCE(e.DELETED, 0) ASC, e.ID_EPISODE ASC LIMIT 1)
  AND COALESCE(el.DELETED, 0) = 0
ORDER BY CASE el.LOCATION_ROLE WHEN 'narrative' THEN 0 WHEN 'filming' THEN 1 ELSE 2 END ASC,
         el.DISPLAY_ORDER ASC, l.LOCATION_NAME ASC, l.ID_LOCATION ASC, el.LOCATION_ROLE ASC;

-- 3. Prompt path: "series with an episode filmed at Arlington National Cemetery".
SELECT DISTINCT s.ID_SERIE, s.SERIE_TITLE, s.DAT_FIRST_AIR, s.IMDB_RATING_WEIGHTED
FROM T_WC_T2S_EPISODE_LOCATION el
JOIN T_WC_T2S_EPISODE e ON e.ID_EPISODE = el.ID_EPISODE
JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = e.ID_SERIE
JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = el.ID_LOCATION AND l.DELETED = 0
WHERE l.LOCATION_NAME = 'Arlington National Cemetery' AND el.LOCATION_ROLE = 'filming'
  AND COALESCE(el.DELETED, 0) = 0
ORDER BY s.IMDB_RATING_WEIGHTED DESC;

-- 4. Cost of the location collection on the busiest place (the 762-episode list).
SELECT el.ID_LOCATION, l.LOCATION_NAME, COUNT(*) AS N
FROM T_WC_T2S_EPISODE_LOCATION el JOIN T_WC_T2S_LOCATION l ON l.ID_LOCATION = el.ID_LOCATION
GROUP BY el.ID_LOCATION, l.LOCATION_NAME ORDER BY N DESC LIMIT 3;
