-- FASTAPI-TEXT2SQL-360: census of the lexical pool that would replace the ChromaDB collections.
--
-- Read-only, voie 1. Written 2026-11-01 for PROVIDER-INDEP-004 (can RapidFuzz alone replace the
-- OpenAI embeddings?). Questions answered:
--   A. Size of each pool, per entity family: living rows, rows with a distinct French name, and
--      distinct labels once case and accents are folded (the utf8mb4_unicode_ci collation does it).
--   B. Movies and series that the ChromaDB builder leaves out (no TMDb 'fr' LANG row, or no
--      ID_WIKIDATA: embedding-update.py:565, 616-617), and how popular they are.
--   C. Size of a multilingual surface-form pool for movies and series (EN + FR + original title),
--      what the TMDb LANG table would add in other languages, and how stale ALIASES is.
--   D. Cross-form ambiguity: a folded label carried by two living movies or more, any form.
--   E. The hard cases of the 1.1.19 campaigns: does an exact folded lookup on any form find them,
--      and how wide is a token LIKE candidate set?
--   F. Awards: what the synonym table would have to cover.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT 'A. pool sizes' AS SECTION;

SELECT 'movie' AS FAMILY, COUNT(*) AS LIVING_ROWS,
       SUM(MOVIE_TITLE_FR IS NOT NULL AND MOVIE_TITLE_FR <> '' AND MOVIE_TITLE_FR <> MOVIE_TITLE) AS FR_DIFFERS,
       SUM(ORIGINAL_TITLE IS NOT NULL AND ORIGINAL_TITLE <> '' AND ORIGINAL_TITLE <> MOVIE_TITLE) AS ORIG_DIFFERS,
       COUNT(DISTINCT MOVIE_TITLE) AS DISTINCT_FOLDED_EN
  FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'serie', COUNT(*),
       SUM(SERIE_TITLE_FR IS NOT NULL AND SERIE_TITLE_FR <> '' AND SERIE_TITLE_FR <> SERIE_TITLE),
       SUM(ORIGINAL_TITLE IS NOT NULL AND ORIGINAL_TITLE <> '' AND ORIGINAL_TITLE <> SERIE_TITLE),
       COUNT(DISTINCT SERIE_TITLE)
  FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'company', COUNT(*), NULL, NULL, COUNT(DISTINCT COMPANY_NAME) FROM T_WC_T2S_COMPANY WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'network', COUNT(*), NULL, NULL, COUNT(DISTINCT NETWORK_NAME) FROM T_WC_T2S_NETWORK WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'topic', COUNT(*), SUM(TOPIC_NAME_FR IS NOT NULL AND TOPIC_NAME_FR <> '' AND TOPIC_NAME_FR <> TOPIC_NAME), NULL, COUNT(DISTINCT TOPIC_NAME)
  FROM T_WC_T2S_TOPIC WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'award', COUNT(*), SUM(AWARD_NAME_FR IS NOT NULL AND AWARD_NAME_FR <> '' AND AWARD_NAME_FR <> AWARD_NAME), NULL, COUNT(DISTINCT AWARD_NAME)
  FROM T_WC_T2S_AWARD WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'nomination', COUNT(*), SUM(NOMINATION_NAME_FR IS NOT NULL AND NOMINATION_NAME_FR <> '' AND NOMINATION_NAME_FR <> NOMINATION_NAME), NULL, COUNT(DISTINCT NOMINATION_NAME)
  FROM T_WC_T2S_NOMINATION WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'list', COUNT(*), SUM(LIST_NAME_FR IS NOT NULL AND LIST_NAME_FR <> '' AND LIST_NAME_FR <> LIST_NAME), NULL, COUNT(DISTINCT LIST_NAME)
  FROM T_WC_T2S_LIST WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'collection', COUNT(*), SUM(COLLECTION_NAME_FR IS NOT NULL AND COLLECTION_NAME_FR <> '' AND COLLECTION_NAME_FR <> COLLECTION_NAME), NULL, COUNT(DISTINCT COLLECTION_NAME)
  FROM T_WC_T2S_COLLECTION WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'movement', COUNT(*), SUM(MOVEMENT_NAME_FR IS NOT NULL AND MOVEMENT_NAME_FR <> '' AND MOVEMENT_NAME_FR <> MOVEMENT_NAME), NULL, COUNT(DISTINCT MOVEMENT_NAME)
  FROM T_WC_T2S_MOVEMENT WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'death', COUNT(*), SUM(DEATH_NAME_FR IS NOT NULL AND DEATH_NAME_FR <> '' AND DEATH_NAME_FR <> DEATH_NAME), NULL, COUNT(DISTINCT DEATH_NAME)
  FROM T_WC_T2S_DEATH WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'group', COUNT(*), SUM(GROUP_NAME_FR IS NOT NULL AND GROUP_NAME_FR <> '' AND GROUP_NAME_FR <> GROUP_NAME), NULL, COUNT(DISTINCT GROUP_NAME)
  FROM T_WC_T2S_GROUP WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'location', COUNT(*), SUM(LOCATION_NAME_FR IS NOT NULL AND LOCATION_NAME_FR <> '' AND LOCATION_NAME_FR <> LOCATION_NAME), NULL, COUNT(DISTINCT LOCATION_NAME)
  FROM T_WC_T2S_LOCATION WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'source_work', COUNT(*), SUM(SOURCE_WORK_NAME_FR IS NOT NULL AND SOURCE_WORK_NAME_FR <> '' AND SOURCE_WORK_NAME_FR <> SOURCE_WORK_NAME), NULL, COUNT(DISTINCT SOURCE_WORK_NAME)
  FROM T_WC_T2S_SOURCE_WORK WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'person', COUNT(*), NULL, NULL, COUNT(DISTINCT PERSON_NAME) FROM T_WC_T2S_PERSON WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'person_alias', COUNT(*), NULL, NULL, COUNT(DISTINCT PERSON_NAME) FROM T_WC_T2S_PERSON_ALSO_KNOWN_AS;

SELECT 'B. rows the ChromaDB builder leaves out' AS SECTION;

SELECT 'movie' AS FAMILY,
       COUNT(*) AS LIVING_ROWS,
       SUM(l.ID_MOVIE IS NULL) AS NO_TMDB_FR_ROW,
       SUM(COALESCE(m.ID_WIKIDATA, '') = '') AS NO_WIKIDATA,
       SUM(l.ID_MOVIE IS NULL OR COALESCE(m.ID_WIKIDATA, '') = '') AS EXCLUDED,
       SUM((l.ID_MOVIE IS NULL OR COALESCE(m.ID_WIKIDATA, '') = '') AND COALESCE(m.IMDB_VOTES, 0) >= 1000) AS EXCLUDED_1K_VOTES,
       SUM(COALESCE(m.IMDB_VOTES, 0) >= 1000) AS ALL_1K_VOTES,
       SUM((l.ID_MOVIE IS NULL OR COALESCE(m.ID_WIKIDATA, '') = '') AND COALESCE(m.IMDB_VOTES, 0) >= 10000) AS EXCLUDED_10K_VOTES,
       SUM(COALESCE(m.IMDB_VOTES, 0) >= 10000) AS ALL_10K_VOTES
  FROM T_WC_T2S_MOVIE m
  LEFT JOIN (SELECT DISTINCT ID_MOVIE FROM T_WC_TMDB_MOVIE_LANG WHERE LANG = 'fr') l ON l.ID_MOVIE = m.ID_MOVIE
 WHERE COALESCE(m.DELETED, 0) = 0;

SELECT 'serie' AS FAMILY,
       COUNT(*) AS LIVING_ROWS,
       SUM(l.ID_SERIE IS NULL) AS NO_TMDB_FR_ROW,
       SUM(COALESCE(s.ID_WIKIDATA, '') = '') AS NO_WIKIDATA,
       SUM(l.ID_SERIE IS NULL OR COALESCE(s.ID_WIKIDATA, '') = '') AS EXCLUDED,
       SUM((l.ID_SERIE IS NULL OR COALESCE(s.ID_WIKIDATA, '') = '') AND COALESCE(s.IMDB_VOTES, 0) >= 1000) AS EXCLUDED_1K_VOTES,
       SUM(COALESCE(s.IMDB_VOTES, 0) >= 1000) AS ALL_1K_VOTES
  FROM T_WC_T2S_SERIE s
  LEFT JOIN (SELECT DISTINCT ID_SERIE FROM T_WC_TMDB_SERIE_LANG WHERE LANG = 'fr') l ON l.ID_SERIE = s.ID_SERIE
 WHERE COALESCE(s.DELETED, 0) = 0;

-- The ten most voted movies left out of the collection.
SELECT m.ID_MOVIE, m.MOVIE_TITLE, m.RELEASE_YEAR, m.IMDB_VOTES,
       (l.ID_MOVIE IS NULL) AS NO_TMDB_FR_ROW, (COALESCE(m.ID_WIKIDATA, '') = '') AS NO_WIKIDATA
  FROM T_WC_T2S_MOVIE m
  LEFT JOIN (SELECT DISTINCT ID_MOVIE FROM T_WC_TMDB_MOVIE_LANG WHERE LANG = 'fr') l ON l.ID_MOVIE = m.ID_MOVIE
 WHERE COALESCE(m.DELETED, 0) = 0 AND (l.ID_MOVIE IS NULL OR COALESCE(m.ID_WIKIDATA, '') = '')
 ORDER BY m.IMDB_VOTES DESC
 LIMIT 10;

SELECT 'C. surface-form pool for movies and series' AS SECTION;

SELECT 'movie' AS FAMILY, COUNT(*) AS FORMS, COUNT(DISTINCT FORM) AS DISTINCT_FOLDED_FORMS
  FROM (SELECT ID_MOVIE, MOVIE_TITLE AS FORM FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(MOVIE_TITLE, '') <> ''
        UNION
        SELECT ID_MOVIE, MOVIE_TITLE_FR FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(MOVIE_TITLE_FR, '') <> ''
        UNION
        SELECT ID_MOVIE, ORIGINAL_TITLE FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(ORIGINAL_TITLE, '') <> '') f
UNION ALL
SELECT 'serie', COUNT(*), COUNT(DISTINCT FORM)
  FROM (SELECT ID_SERIE, SERIE_TITLE AS FORM FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(SERIE_TITLE, '') <> ''
        UNION
        SELECT ID_SERIE, SERIE_TITLE_FR FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(SERIE_TITLE_FR, '') <> ''
        UNION
        SELECT ID_SERIE, ORIGINAL_TITLE FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(ORIGINAL_TITLE, '') <> '') f;

-- What the TMDb LANG table would add: titles per language, top 15 languages.
SELECT LANG, COUNT(*) AS ROWS_WITH_TITLE, COUNT(DISTINCT ID_MOVIE) AS MOVIES
  FROM T_WC_TMDB_MOVIE_LANG
 WHERE COALESCE(TITLE, '') <> '' AND COALESCE(DELETED, 0) = 0
 GROUP BY LANG
 ORDER BY ROWS_WITH_TITLE DESC
 LIMIT 15;

SELECT 'movie' AS FAMILY, SUM(COALESCE(ALIASES, '') <> '') AS WITH_ALIASES, SUM(COALESCE(WIKIDATA_TITLE, '') <> '') AS WITH_WIKIDATA_TITLE,
       SUM(COALESCE(WIKIDATA_TITLE, '') <> '' AND WIKIDATA_TITLE <> MOVIE_TITLE AND WIKIDATA_TITLE <> COALESCE(MOVIE_TITLE_FR, '')) AS WIKIDATA_TITLE_NEW
  FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0
UNION ALL
SELECT 'serie', SUM(COALESCE(ALIASES, '') <> ''), SUM(COALESCE(WIKIDATA_TITLE, '') <> ''),
       SUM(COALESCE(WIKIDATA_TITLE, '') <> '' AND WIKIDATA_TITLE <> SERIE_TITLE AND WIKIDATA_TITLE <> COALESCE(SERIE_TITLE_FR, ''))
  FROM T_WC_T2S_SERIE WHERE COALESCE(DELETED, 0) = 0;

SELECT 'D. cross-form ambiguity, movies' AS SECTION;

-- A folded form carried by two living movies or more, whatever the form (EN, FR or original).
SELECT COUNT(*) AS AMBIGUOUS_FORMS, SUM(N) AS MOVIES_INVOLVED, MAX(N) AS MAX_MOVIES_PER_FORM
  FROM (SELECT FORM, COUNT(DISTINCT ID_MOVIE) AS N
          FROM (SELECT ID_MOVIE, MOVIE_TITLE AS FORM FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(MOVIE_TITLE, '') <> ''
                UNION
                SELECT ID_MOVIE, MOVIE_TITLE_FR FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(MOVIE_TITLE_FR, '') <> ''
                UNION
                SELECT ID_MOVIE, ORIGINAL_TITLE FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND COALESCE(ORIGINAL_TITLE, '') <> '') f
         GROUP BY FORM
        HAVING COUNT(DISTINCT ID_MOVIE) >= 2) a;

-- Same, restricted to movies with 1,000 IMDb votes or more (the ones people ask about).
SELECT COUNT(*) AS AMBIGUOUS_FORMS_1K, SUM(N) AS MOVIES_INVOLVED_1K
  FROM (SELECT FORM, COUNT(DISTINCT ID_MOVIE) AS N
          FROM (SELECT ID_MOVIE, MOVIE_TITLE AS FORM FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND IMDB_VOTES >= 1000
                UNION
                SELECT ID_MOVIE, MOVIE_TITLE_FR FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND IMDB_VOTES >= 1000 AND COALESCE(MOVIE_TITLE_FR, '') <> ''
                UNION
                SELECT ID_MOVIE, ORIGINAL_TITLE FROM T_WC_T2S_MOVIE WHERE COALESCE(DELETED, 0) = 0 AND IMDB_VOTES >= 1000 AND COALESCE(ORIGINAL_TITLE, '') <> '') f
         GROUP BY FORM
        HAVING COUNT(DISTINCT ID_MOVIE) >= 2) a;

SELECT 'E. hard cases of the 1.1.19 campaigns' AS SECTION;

-- Exact folded lookup on any of the three forms; the best match by IMDb votes, and how many movies match.
SELECT q.SOUGHT,
       COUNT(m.ID_MOVIE) AS EXACT_HITS,
       SUBSTRING_INDEX(GROUP_CONCAT(CONCAT(m.ID_MOVIE, ' ', m.MOVIE_TITLE, ' (', COALESCE(m.RELEASE_YEAR, '?'), ', ', COALESCE(m.IMDB_VOTES, 0), ' votes)')
                                    ORDER BY m.IMDB_VOTES DESC SEPARATOR ' | '), ' | ', 3) AS TOP_HITS
  FROM (SELECT '2001, l''Odyssée de l''espace' AS SOUGHT UNION ALL SELECT '2001 : L''Odyssée de l''espace'
        UNION ALL SELECT 'Step Up' UNION ALL SELECT 'Footloose' UNION ALL SELECT 'Dirty Dancing' UNION ALL SELECT 'Flashdance'
        UNION ALL SELECT 'Saturday Night Fever' UNION ALL SELECT '12 Monkeys' UNION ALL SELECT 'Twelve Monkeys'
        UNION ALL SELECT 'L''Armée des 12 singes' UNION ALL SELECT 'The Dark Knight' UNION ALL SELECT 'dark knight'
        UNION ALL SELECT 'Le Grand Sommeil' UNION ALL SELECT 'La Veuve Insatiable' UNION ALL SELECT 'Vingt-quatre heures pour tuer'
        UNION ALL SELECT 'Noroît' UNION ALL SELECT 'Psychose' UNION ALL SELECT 'Docteur Folamour' UNION ALL SELECT 'Sailor et Lula'
        UNION ALL SELECT 'La Chevauchée fantastique' UNION ALL SELECT 'the big lebowski' UNION ALL SELECT 'amelie') q
  LEFT JOIN T_WC_T2S_MOVIE m
    ON COALESCE(m.DELETED, 0) = 0
   AND (m.MOVIE_TITLE = q.SOUGHT OR m.MOVIE_TITLE_FR = q.SOUGHT OR m.ORIGINAL_TITLE = q.SOUGHT)
 GROUP BY q.SOUGHT;

-- Width of a token candidate set (LIKE on the longest token, any form), the RapidFuzz fallback today.
SELECT q.TOKEN, COUNT(*) AS CANDIDATES
  FROM (SELECT 'odyssée' AS TOKEN UNION ALL SELECT 'monkeys' UNION ALL SELECT 'strangelove' UNION ALL SELECT 'footloose'
        UNION ALL SELECT 'knight' UNION ALL SELECT 'lebowski' UNION ALL SELECT 'sommeil' UNION ALL SELECT 'amélie') q
  JOIN T_WC_T2S_MOVIE m
    ON COALESCE(m.DELETED, 0) = 0
   AND (m.MOVIE_TITLE LIKE CONCAT('%', q.TOKEN, '%') OR m.MOVIE_TITLE_FR LIKE CONCAT('%', q.TOKEN, '%') OR m.ORIGINAL_TITLE LIKE CONCAT('%', q.TOKEN, '%'))
 GROUP BY q.TOKEN;

SELECT 'F. awards: what a synonym table must cover' AS SECTION;

-- Awards whose name contains a common short form, with their volume.
SELECT q.SHORT_FORM, COUNT(a.ID_AWARD) AS AWARDS_MATCHING,
       SUBSTRING_INDEX(GROUP_CONCAT(CONCAT(a.AWARD_NAME, ' / ', COALESCE(a.AWARD_NAME_FR, '-'), ' (', COALESCE(a.MOVIE_COUNT, 0) + COALESCE(a.SERIE_COUNT, 0), ')')
                                    ORDER BY COALESCE(a.MOVIE_COUNT, 0) + COALESCE(a.SERIE_COUNT, 0) DESC SEPARATOR ' | '), ' | ', 4) AS TOP_AWARDS
  FROM (SELECT 'Oscar' AS SHORT_FORM UNION ALL SELECT 'Academy Award' UNION ALL SELECT 'BAFTA' UNION ALL SELECT 'Razzie'
        UNION ALL SELECT 'Golden Raspberry' UNION ALL SELECT 'Palme' UNION ALL SELECT 'César' UNION ALL SELECT 'Golden Globe'
        UNION ALL SELECT 'Emmy' UNION ALL SELECT 'Lion' UNION ALL SELECT 'Ours' UNION ALL SELECT 'Bear') q
  LEFT JOIN T_WC_T2S_AWARD a
    ON COALESCE(a.DELETED, 0) = 0
   AND (a.AWARD_NAME LIKE CONCAT('%', q.SHORT_FORM, '%') OR a.AWARD_NAME_FR LIKE CONCAT('%', q.SHORT_FORM, '%'))
 GROUP BY q.SHORT_FORM;

-- The 25 awards with the most movies and series: the head the synonym table must cover first.
SELECT a.ID_AWARD, a.AWARD_NAME, a.AWARD_NAME_FR, COALESCE(a.MOVIE_COUNT, 0) + COALESCE(a.SERIE_COUNT, 0) AS VOLUME
  FROM T_WC_T2S_AWARD a
 WHERE COALESCE(a.DELETED, 0) = 0
 ORDER BY VOLUME DESC
 LIMIT 25;

-- Distribution of award volume: how many awards would ever be asked about.
SELECT SUM(V >= 100) AS AWARDS_100_PLUS, SUM(V BETWEEN 10 AND 99) AS AWARDS_10_99, SUM(V BETWEEN 1 AND 9) AS AWARDS_1_9, SUM(V = 0) AS AWARDS_0
  FROM (SELECT COALESCE(MOVIE_COUNT, 0) + COALESCE(SERIE_COUNT, 0) AS V FROM T_WC_T2S_AWARD WHERE COALESCE(DELETED, 0) = 0) x;
