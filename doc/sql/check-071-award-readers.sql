-- Award lists once the link tables hold one row per win: the readers' new queries on the live base.
--
-- Read-only, voie 1. Written 2026-11-10. TMDB-MOVIE-PREPROCESS-071 turns a row of
-- T_WC_T2S_MOVIE_AWARD, T_WC_T2S_SERIE_AWARD and T_WC_T2S_PERSON_AWARD into one win (one
-- statement and one year), so the same (entity, award) pair can sit on several rows. The
-- readers were rewritten to list a pair once:
--   - fastapi-text2sql, entity endpoints (main.py): the `awards` list of /movies, /series,
--     /persons and the three lists of /awards read the link table through a grouped subquery;
--   - tmdb-front 1.0.84 (lib/movie.inc.php, serie.inc.php, person.inc.php, award.inc.php):
--     GROUP BY on the award, COUNT(DISTINCT), grouped subquery.
--
-- This file runs those queries as written (with a LIMIT, as the pagination adds one) on the
-- entity that holds the most link rows, and compares for each list the rows the new query
-- returns with the distinct pairs of the link table. NEW_ROWS must equal DISTINCT_PAIRS in
-- every line of section 2. It can run before the migration (one row per pair: LINK_ROWS equals
-- DISTINCT_PAIRS too) and after the first build (LINK_ROWS may then be higher).

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SET @m := (SELECT ID_MOVIE FROM T_WC_T2S_MOVIE_AWARD GROUP BY ID_MOVIE ORDER BY COUNT(*) DESC, ID_MOVIE LIMIT 1);
SET @s := (SELECT ID_SERIE FROM T_WC_T2S_SERIE_AWARD GROUP BY ID_SERIE ORDER BY COUNT(*) DESC, ID_SERIE LIMIT 1);
SET @p := (SELECT ID_PERSON FROM T_WC_T2S_PERSON_AWARD GROUP BY ID_PERSON ORDER BY COUNT(*) DESC, ID_PERSON LIMIT 1);
SET @a := 269;   -- Academy Award for Best Actress: persons, and Katharine Hepburn four times
SET @am := (SELECT ID_AWARD FROM T_WC_T2S_MOVIE_AWARD GROUP BY ID_AWARD ORDER BY COUNT(*) DESC, ID_AWARD LIMIT 1);
SET @as := (SELECT ID_AWARD FROM T_WC_T2S_SERIE_AWARD GROUP BY ID_AWARD ORDER BY COUNT(*) DESC, ID_AWARD LIMIT 1);

SELECT '1. entities and awards under test' AS SECTION;
SELECT @m AS ID_MOVIE, @s AS ID_SERIE, @p AS ID_PERSON, @a AS ID_AWARD_PERSONS, @am AS ID_AWARD_MOVIES, @as AS ID_AWARD_SERIES;

SELECT '2. rows of each new list against the distinct pairs of the link table' AS SECTION;
SELECT 'api movie awards' AS LIST,
       (SELECT COUNT(*) FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m GROUP BY ID_AWARD) ma
        JOIN T_WC_T2S_AWARD a ON ma.ID_AWARD = a.ID_AWARD) AS NEW_ROWS,
       (SELECT COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m) AS DISTINCT_PAIRS,
       (SELECT COUNT(*) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m) AS LINK_ROWS
UNION ALL
SELECT 'api series awards',
       (SELECT COUNT(*) FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_SERIE_AWARD WHERE ID_SERIE = @s GROUP BY ID_AWARD) sa
        JOIN T_WC_T2S_AWARD a ON sa.ID_AWARD = a.ID_AWARD),
       (SELECT COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_SERIE_AWARD WHERE ID_SERIE = @s),
       (SELECT COUNT(*) FROM T_WC_T2S_SERIE_AWARD WHERE ID_SERIE = @s)
UNION ALL
SELECT 'api person awards',
       (SELECT COUNT(*) FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_PERSON_AWARD WHERE ID_PERSON = @p GROUP BY ID_AWARD) pa
        JOIN T_WC_T2S_AWARD a ON pa.ID_AWARD = a.ID_AWARD),
       (SELECT COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_PERSON_AWARD WHERE ID_PERSON = @p),
       (SELECT COUNT(*) FROM T_WC_T2S_PERSON_AWARD WHERE ID_PERSON = @p)
UNION ALL
SELECT 'api award movies',
       (SELECT COUNT(*) FROM (SELECT ID_MOVIE, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am GROUP BY ID_MOVIE) ma
        JOIN T_WC_T2S_MOVIE m ON ma.ID_MOVIE = m.ID_MOVIE),
       (SELECT COUNT(DISTINCT j.ID_MOVIE) FROM T_WC_T2S_MOVIE_AWARD j JOIN T_WC_T2S_MOVIE m ON m.ID_MOVIE = j.ID_MOVIE WHERE j.ID_AWARD = @am),
       (SELECT COUNT(*) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am)
UNION ALL
SELECT 'api award series',
       (SELECT COUNT(*) FROM (SELECT ID_SERIE, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_SERIE_AWARD WHERE ID_AWARD = @as GROUP BY ID_SERIE) sa
        JOIN T_WC_T2S_SERIE s ON sa.ID_SERIE = s.ID_SERIE),
       (SELECT COUNT(DISTINCT j.ID_SERIE) FROM T_WC_T2S_SERIE_AWARD j JOIN T_WC_T2S_SERIE s ON s.ID_SERIE = j.ID_SERIE WHERE j.ID_AWARD = @as),
       (SELECT COUNT(*) FROM T_WC_T2S_SERIE_AWARD WHERE ID_AWARD = @as)
UNION ALL
SELECT 'api award persons',
       (SELECT COUNT(*) FROM (SELECT ID_PERSON, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
                              FROM T_WC_T2S_PERSON_AWARD WHERE ID_AWARD = @a GROUP BY ID_PERSON) pa
        JOIN T_WC_T2S_PERSON p ON pa.ID_PERSON = p.ID_PERSON),
       (SELECT COUNT(DISTINCT j.ID_PERSON) FROM T_WC_T2S_PERSON_AWARD j JOIN T_WC_T2S_PERSON p ON p.ID_PERSON = j.ID_PERSON WHERE j.ID_AWARD = @a),
       (SELECT COUNT(*) FROM T_WC_T2S_PERSON_AWARD WHERE ID_AWARD = @a)
UNION ALL
SELECT 'front movie awards',
       (SELECT COUNT(*) FROM (SELECT T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR, MIN(T_WC_T2S_MOVIE_AWARD.DISPLAY_ORDER) AS MIN_DISPLAY_ORDER
                              FROM T_WC_T2S_MOVIE_AWARD
                              INNER JOIN T_WC_T2S_AWARD ON T_WC_T2S_MOVIE_AWARD.ID_AWARD = T_WC_T2S_AWARD.ID_AWARD
                              WHERE T_WC_T2S_MOVIE_AWARD.ID_MOVIE = @m
                              GROUP BY T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR) x),
       (SELECT COUNT(DISTINCT ID_AWARD) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m),
       (SELECT COUNT(*) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m)
UNION ALL
SELECT 'front award movies count',
       (SELECT COUNT(DISTINCT J.ID_MOVIE) FROM T_WC_T2S_MOVIE_AWARD J WHERE J.ID_AWARD = @am),
       (SELECT COUNT(DISTINCT ID_MOVIE) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am),
       (SELECT COUNT(*) FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am);

SELECT '3. api, awards of the movie, the series and the person (first rows, as the endpoint returns them)' AS SECTION;
SELECT a.ID_AWARD, a.AWARD_NAME, a.AWARD_NAME_FR, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_MOVIE_AWARD WHERE ID_MOVIE = @m GROUP BY ID_AWARD) ma
JOIN T_WC_T2S_AWARD a ON ma.ID_AWARD = a.ID_AWARD
ORDER BY ma.DISPLAY_ORDER ASC, a.ID_AWARD ASC
LIMIT 5 OFFSET 0;
SELECT a.ID_AWARD, a.AWARD_NAME, a.AWARD_NAME_FR, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_SERIE_AWARD WHERE ID_SERIE = @s GROUP BY ID_AWARD) sa
JOIN T_WC_T2S_AWARD a ON sa.ID_AWARD = a.ID_AWARD
ORDER BY sa.DISPLAY_ORDER ASC, a.ID_AWARD ASC
LIMIT 5 OFFSET 0;
SELECT a.ID_AWARD, a.AWARD_NAME, a.AWARD_NAME_FR, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_AWARD, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_PERSON_AWARD WHERE ID_PERSON = @p GROUP BY ID_AWARD) pa
JOIN T_WC_T2S_AWARD a ON pa.ID_AWARD = a.ID_AWARD
ORDER BY pa.DISPLAY_ORDER ASC, a.ID_AWARD ASC
LIMIT 5 OFFSET 0;

SELECT '4. api, winners of an award: movies, series, persons (first rows)' AS SECTION;
SELECT m.ID_MOVIE, m.MOVIE_TITLE, m.DAT_RELEASE, ma.DISPLAY_ORDER, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_MOVIE, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am GROUP BY ID_MOVIE) ma
JOIN T_WC_T2S_MOVIE m ON ma.ID_MOVIE = m.ID_MOVIE
ORDER BY ma.DISPLAY_ORDER ASC, m.ID_MOVIE ASC
LIMIT 5 OFFSET 0;
SELECT s.ID_SERIE, s.SERIE_TITLE, s.DAT_FIRST_AIR, sa.DISPLAY_ORDER, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_SERIE, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_SERIE_AWARD WHERE ID_AWARD = @as GROUP BY ID_SERIE) sa
JOIN T_WC_T2S_SERIE s ON sa.ID_SERIE = s.ID_SERIE
ORDER BY sa.DISPLAY_ORDER ASC, s.ID_SERIE ASC
LIMIT 5 OFFSET 0;
SELECT p.ID_PERSON, p.PERSON_NAME, pa.DISPLAY_ORDER, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (SELECT ID_PERSON, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER
      FROM T_WC_T2S_PERSON_AWARD WHERE ID_AWARD = @a GROUP BY ID_PERSON) pa
JOIN T_WC_T2S_PERSON p ON pa.ID_PERSON = p.ID_PERSON
ORDER BY pa.DISPLAY_ORDER ASC, p.ID_PERSON ASC
LIMIT 5 OFFSET 0;

SELECT '5. tmdb-front, awards of the person and movies of the award (first rows)' AS SECTION;
SELECT T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR, MIN(T_WC_T2S_PERSON_AWARD.DISPLAY_ORDER) AS MIN_DISPLAY_ORDER
FROM T_WC_T2S_PERSON_AWARD
INNER JOIN T_WC_T2S_AWARD ON T_WC_T2S_PERSON_AWARD.ID_AWARD = T_WC_T2S_AWARD.ID_AWARD
WHERE T_WC_T2S_PERSON_AWARD.ID_PERSON = @p
GROUP BY T_WC_T2S_AWARD.ID_AWARD, T_WC_T2S_AWARD.AWARD_NAME, T_WC_T2S_AWARD.AWARD_NAME_FR
ORDER BY MIN_DISPLAY_ORDER, T_WC_T2S_AWARD.AWARD_NAME
LIMIT 5;
SELECT M.ID_MOVIE, M.MOVIE_TITLE, J.DISPLAY_ORDER
FROM T_WC_T2S_MOVIE M
JOIN (SELECT ID_MOVIE, MIN(DISPLAY_ORDER) AS DISPLAY_ORDER FROM T_WC_T2S_MOVIE_AWARD WHERE ID_AWARD = @am GROUP BY ID_MOVIE) J ON M.ID_MOVIE = J.ID_MOVIE
ORDER BY J.DISPLAY_ORDER, M.DAT_RELEASE DESC
LIMIT 5;
