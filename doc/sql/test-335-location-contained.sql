-- FASTAPI-TEXT2SQL-335: /locations/{id} with scope=contained, read-only check (voie 1).
--
-- Runs the exact list queries of get_location (scope=contained, no role filter) for
-- France (126), Paris (38), London (21) and the Moon (341): total rows (work and role, the
-- _TOTAL_COUNT of the API), the first rows with their VIA place, and the *_COUNT_CONTAINED
-- values beside the direct counts. Also checks the dedup: no (work, role) twice.
-- Written 2026-10-19.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT '1. Direct and contained counts' AS SECTION;

SELECT l.ID_LOCATION, l.LOCATION_NAME, l.MOVIE_COUNT, l.SERIE_COUNT, l.EPISODE_COUNT,
  (SELECT COUNT(DISTINCT j.ID_MOVIE) FROM T_WC_T2S_LOCATION_ANCESTOR a
     JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
     JOIN T_WC_T2S_MOVIE w ON w.ID_MOVIE = j.ID_MOVIE AND COALESCE(w.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = l.ID_LOCATION) AS MOVIE_COUNT_CONTAINED,
  (SELECT COUNT(DISTINCT j.ID_SERIE) FROM T_WC_T2S_LOCATION_ANCESTOR a
     JOIN T_WC_T2S_SERIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
     JOIN T_WC_T2S_SERIE w ON w.ID_SERIE = j.ID_SERIE AND COALESCE(w.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = l.ID_LOCATION) AS SERIE_COUNT_CONTAINED,
  (SELECT COUNT(DISTINCT j.ID_EPISODE) FROM T_WC_T2S_LOCATION_ANCESTOR a
     JOIN T_WC_T2S_EPISODE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
     JOIN T_WC_T2S_EPISODE w ON w.ID_EPISODE = j.ID_EPISODE AND COALESCE(w.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = l.ID_LOCATION) AS EPISODE_COUNT_CONTAINED
FROM T_WC_T2S_LOCATION l
WHERE l.ID_LOCATION IN (126, 38, 21, 341);

SELECT '2. France (126), movies list, first 8 rows and the total' AS SECTION;

SELECT m.ID_MOVIE, m.MOVIE_TITLE, m.IMDB_RATING_WEIGHTED, ml.LOCATION_ROLE, ml.VIA_ID_LOCATION,
       vl.LOCATION_NAME AS VIA_LOCATION_NAME, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (
    SELECT j.ID_MOVIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_MOVIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 126
) ml
JOIN T_WC_T2S_MOVIE m ON ml.ID_MOVIE = m.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = ml.VIA_ID_LOCATION
WHERE ml.RN = 1
ORDER BY m.IMDB_RATING_WEIGHTED DESC, m.ID_MOVIE ASC, ml.LOCATION_ROLE ASC
LIMIT 8;

SELECT '3. Paris (38), movies list, filming only (role filter), first 5 rows' AS SECTION;

SELECT m.ID_MOVIE, m.MOVIE_TITLE, ml.LOCATION_ROLE, vl.LOCATION_NAME AS VIA_LOCATION_NAME, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (
    SELECT j.ID_MOVIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_MOVIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 38 AND j.LOCATION_ROLE = 'filming'
) ml
JOIN T_WC_T2S_MOVIE m ON ml.ID_MOVIE = m.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = ml.VIA_ID_LOCATION
WHERE ml.RN = 1
ORDER BY m.IMDB_RATING_WEIGHTED DESC, m.ID_MOVIE ASC, ml.LOCATION_ROLE ASC
LIMIT 5;

SELECT '4. London (21), series list, first 5 rows' AS SECTION;

SELECT s.ID_SERIE, s.SERIE_TITLE, sl.LOCATION_ROLE, vl.LOCATION_NAME AS VIA_LOCATION_NAME, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (
    SELECT j.ID_SERIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_SERIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_SERIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 21
) sl
JOIN T_WC_T2S_SERIE s ON sl.ID_SERIE = s.ID_SERIE AND COALESCE(s.DELETED, 0) = 0
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = sl.VIA_ID_LOCATION
WHERE sl.RN = 1
ORDER BY s.IMDB_RATING_WEIGHTED DESC, s.ID_SERIE ASC, sl.LOCATION_ROLE ASC
LIMIT 5;

SELECT '5. France (126), episodes list, first 5 rows' AS SECTION;

SELECT e.ID_EPISODE, s.SERIE_TITLE, e.SEASON_NUMBER, e.EPISODE_NUMBER, el.LOCATION_ROLE,
       vl.LOCATION_NAME AS VIA_LOCATION_NAME, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (
    SELECT j.ID_EPISODE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_EPISODE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_EPISODE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 126
) el
JOIN T_WC_T2S_EPISODE e ON el.ID_EPISODE = e.ID_EPISODE AND COALESCE(e.DELETED, 0) = 0
JOIN T_WC_T2S_SERIE s ON e.ID_SERIE = s.ID_SERIE
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = el.VIA_ID_LOCATION
WHERE el.RN = 1
ORDER BY s.IMDB_RATING_WEIGHTED DESC, e.ID_SERIE ASC, e.SEASON_NUMBER ASC, e.EPISODE_NUMBER ASC, el.LOCATION_ROLE ASC
LIMIT 5;

SELECT '6. The Moon (341), movies list: only the Moon itself as VIA' AS SECTION;

SELECT vl.LOCATION_NAME AS VIA_LOCATION_NAME, COUNT(*) AS N
FROM (
    SELECT j.ID_MOVIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_MOVIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 341
) ml
JOIN T_WC_T2S_MOVIE m ON ml.ID_MOVIE = m.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = ml.VIA_ID_LOCATION
WHERE ml.RN = 1
GROUP BY vl.LOCATION_NAME;

SELECT '7. Dedup check: (movie, role) pairs returned twice for France, must be 0' AS SECTION;

SELECT COUNT(*) AS DUPLICATES FROM (
  SELECT ml.ID_MOVIE, ml.LOCATION_ROLE, COUNT(*) AS N
  FROM (
      SELECT j.ID_MOVIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
             ROW_NUMBER() OVER (PARTITION BY j.ID_MOVIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
      FROM T_WC_T2S_LOCATION_ANCESTOR a
      JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
      WHERE a.ID_ANCESTOR = 126
  ) ml
  WHERE ml.RN = 1
  GROUP BY ml.ID_MOVIE, ml.LOCATION_ROLE
  HAVING N > 1
) d;

SELECT '8. EXPLAIN of the France movies list' AS SECTION;

EXPLAIN
SELECT m.ID_MOVIE, COUNT(*) OVER() AS _TOTAL_COUNT
FROM (
    SELECT j.ID_MOVIE, j.LOCATION_ROLE, j.ID_LOCATION AS VIA_ID_LOCATION,
           ROW_NUMBER() OVER (PARTITION BY j.ID_MOVIE, j.LOCATION_ROLE ORDER BY a.DEPTH ASC, j.ID_LOCATION ASC) AS RN
    FROM T_WC_T2S_LOCATION_ANCESTOR a
    JOIN T_WC_T2S_MOVIE_LOCATION j ON j.ID_LOCATION = a.ID_LOCATION AND COALESCE(j.DELETED, 0) = 0
    WHERE a.ID_ANCESTOR = 126
) ml
JOIN T_WC_T2S_MOVIE m ON ml.ID_MOVIE = m.ID_MOVIE AND COALESCE(m.DELETED, 0) = 0
JOIN T_WC_T2S_LOCATION vl ON vl.ID_LOCATION = ml.VIA_ID_LOCATION
WHERE ml.RN = 1
ORDER BY m.IMDB_RATING_WEIGHTED DESC, m.ID_MOVIE ASC, ml.LOCATION_ROLE ASC
LIMIT 50;
