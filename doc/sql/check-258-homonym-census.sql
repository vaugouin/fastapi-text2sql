-- FASTAPI-TEXT2SQL-258: census of exact homonyms per entity family.
--
-- Read-only, voie 1. Written 2026-10-19 for the design note of the ticket. For each family:
-- how many labels are carried by two living rows or more, how many rows that is, and how
-- often a volume tie-break would pick a clear winner (the first row has at least three
-- times the volume of the second), a narrow one, or a tie. Volume: places, movies + series
-- + episodes linked; persons, POPULARITY; movies and series, IMDB_VOTES; companies,
-- collections and awards, movies + series; networks, series.

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT 'location' AS SECTION;

SELECT 'location' AS FAMILY,
       (SELECT COUNT(*) FROM T_WC_T2S_LOCATION WHERE COALESCE(DELETED, 0) = 0) AS LIVING_ROWS,
       COUNT(DISTINCT g.LABEL) AS HOMONYM_LABELS,
       COUNT(*) AS HOMONYM_ROWS,
       SUM(g.RN = 1 AND g.VOL > 0 AND g.VOL >= 3 * g.V2) AS CLEAR_WINNER,
       SUM(g.RN = 1 AND g.VOL > g.V2 AND g.VOL < 3 * g.V2) AS NARROW_WINNER,
       SUM(g.RN = 1 AND g.VOL = g.V2) AS TIE
FROM (
  SELECT x.LABEL, x.VOL,
         ROW_NUMBER() OVER (PARTITION BY x.LABEL ORDER BY x.VOL DESC) AS RN,
         LEAD(x.VOL) OVER (PARTITION BY x.LABEL ORDER BY x.VOL DESC) AS V2
  FROM (SELECT t.LOCATION_NAME AS LABEL, COALESCE(t.MOVIE_COUNT,0)+COALESCE(t.SERIE_COUNT,0)+COALESCE(t.EPISODE_COUNT,0) AS VOL
          FROM T_WC_T2S_LOCATION t
          JOIN (SELECT LOCATION_NAME AS L FROM T_WC_T2S_LOCATION WHERE COALESCE(DELETED, 0) = 0 AND LOCATION_NAME <> ''
                 GROUP BY LOCATION_NAME HAVING COUNT(*) >= 2) d ON d.L = t.LOCATION_NAME
         WHERE COALESCE(t.DELETED, 0) = 0) x
) g;

SELECT t.LOCATION_NAME AS LABEL, COUNT(*) AS N, SUM(COALESCE(t.MOVIE_COUNT,0)+COALESCE(t.SERIE_COUNT,0)+COALESCE(t.EPISODE_COUNT,0)) AS TOTAL_VOLUME
FROM T_WC_T2S_LOCATION t
WHERE COALESCE(t.DELETED, 0) = 0 AND t.LOCATION_NAME <> ''
GROUP BY t.LOCATION_NAME
HAVING COUNT(*) >= 2
ORDER BY TOTAL_VOLUME DESC
LIMIT 10;

