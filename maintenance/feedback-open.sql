SELECT '0. All feedback, by status and rating' AS SECTION;
SELECT ANALYSIS_STATUS, RATING, (COMMENT IS NOT NULL AND COMMENT <> '') AS HAS_COMMENT, COUNT(*) AS N,
       MIN(TIM_CREATED) AS FIRST_AT, MAX(TIM_CREATED) AS LAST_AT
FROM T_WC_T2S_FEEDBACK
WHERE (DELETED IS NULL OR DELETED = 0)
GROUP BY ANALYSIS_STATUS, RATING, HAS_COMMENT
ORDER BY ANALYSIS_STATUS, RATING;

SELECT '1. Open: thumbs down, or any rating with a comment' AS SECTION;
SELECT ID_FEEDBACK, TIM_CREATED, CLIENT, UI_LANGUAGE, RATING, COMMENT, QUESTION, QUESTION_HASHED,
       REQUEST_ID, API_VERSION, RESULT_ENTITY, ANALYSIS_STATUS
FROM T_WC_T2S_FEEDBACK
WHERE (DELETED IS NULL OR DELETED = 0)
  AND ANALYSIS_STATUS = 'new'
  AND (RATING < 0 OR (COMMENT IS NOT NULL AND COMMENT <> ''))
ORDER BY QUESTION_HASHED, TIM_CREATED;

SELECT '2. Last 20 rows, any rating' AS SECTION;
SELECT ID_FEEDBACK, TIM_CREATED, CLIENT, UI_LANGUAGE, RATING, LEFT(COMMENT, 80) AS COMMENT_START,
       LEFT(QUESTION, 80) AS QUESTION_START, API_VERSION, ANALYSIS_STATUS
FROM T_WC_T2S_FEEDBACK
WHERE (DELETED IS NULL OR DELETED = 0)
ORDER BY ID_FEEDBACK DESC
LIMIT 20;
