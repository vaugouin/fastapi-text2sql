def fold(name):
    """A place name folded for lookup: lowercase, accents stripped, a leading "the" dropped."""
    text = unicodedata.normalize("NFKD", str(name or "")).encode("ascii", "ignore").decode("ascii")
    text = " ".join(text.lower().replace("\u2019", "'").split())
    return text[4:] if text.startswith("the ") else text


_BY_NAME = {}
for _code, (_en, _fr) in list(NAMES.items()) + list(NO_FLAG.items()):
    _BY_NAME.setdefault(fold(_en), _code)
    _BY_NAME.setdefault(fold(_fr), _code)
for _alias, _code in ALIASES.items():
    _BY_NAME[fold(_alias)] = _code


def code_for_name(name):
    """The ISO code of a country named in English or French, or None."""
    return _BY_NAME.get(fold(name))


def is_code(value):
    """True for a two-letter string that is a known code (with a flag or not), any case."""
    text = str(value or "").strip().upper()
    return len(text) == 2 and (text in NAMES or text in NO_FLAG)


def numeric_for(code):
    """The ISO 3166-1 numeric code (a three-digit string) of an alpha-2 code, or None."""
    return NUMERIC.get(str(code or "").strip().upper())


def names_for(code):
    """{"en", "fr"} for a code, or None."""
    pair = NAMES.get(str(code or "").upper()) or NO_FLAG.get(str(code or "").upper())
    return {"en": pair[0], "fr": pair[1]} if pair else None
